export const ALL_ORGANIZATIONS: OrgItem[] = [
  ...PREMIER_INSTITUTIONS,
  ...SEMICONDUCTOR_100_ORGS,
];

/**
 * Lookup organization by slug with case/hyphen insensitivity fallback
 */
export function getStaticOrgBySlug(slug: string): OrgItem | undefined {
  const normalized = slug.toLowerCase().trim();
  return ALL_ORGANIZATIONS.find(
    (org) => org.slug.toLowerCase() === normalized ||
             org.name.toLowerCase().replace(/[^a-z0-9]+/g, "-") === normalized
  );
}
